#!/usr/bin/env python3
"""Generates the ArUco marker models the ROI targets are tagged with.

Why the markers exist.  A search-and-rescue prop made of primitives is something a
human can see but nothing a detector can score reliably.  Pairing each ROI with a
fiducial makes detection deterministic: a run either read marker 5 or it did not, and
the run manifest says exactly where marker 5 is in ENU and WGS84.

Why one model directory per id rather than one parametrised model.  gz-sim renders
with Ogre2, which ignores SDF ``<material><script>`` -- that is a gazebo-classic
feature, so a single model with one material technique per id would render as a plain
white plate.  (``models/grasspatch_visual`` ships a ``grass.material`` script that is
in fact dead code; it only looks right because the same model also sets a PBR
``albedo_map``.  Mirror the PBR block, not the script.)  Eight directories is more
files but they are generated, not maintained.

Why the marker is a plane inside a model file.  There is exactly one plane collision
allowed per world, and ``uavsim/verify.py`` enforces it by counting ``<plane>`` in the
world text.  Geometry that arrives through ``<include>`` never enters that text, so a
plane here is free -- and a plane gives unambiguous top-face UV, which a box does not.

Sizing, from the real camera.  The gimbal camera is 640x480 with a 2.0 rad horizontal
FOV (``models/gimbal_small_3d/model.sdf``), so the ground swath is 3.1148*h and the
plate spans 205.5*S/h pixels.  A 4x4 marker with its black border is 6 modules across,
and OpenCV needs roughly 3 px per module:

    altitude   GSD      3.0 m plate   px per module
      10 m     4.9 cm      62 px          8.2
      15 m     7.3 cm      41 px          5.5
      20 m     9.7 cm      31 px          4.1     <- comfortable
      25 m    12.2 cm      25 px          3.3     marginal
      30 m    14.6 cm      21 px          2.7     below the floor

Hence a 3.0 m plate carrying a 2.4 m marker: readable from the 15-25 m a survey flies,
where the old 2 m plate gave out above ~20 m.

The PNGs are committed alongside this script so that ``uavsim world`` works on a
machine with no OpenCV; ``--check`` regenerates them in memory and byte-compares, so a
test can prove the committed files still match.  OpenCV is therefore an optional
authoring dependency, never a runtime one.

    python3 tools/gen_aruco_textures.py --ids 0-9
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

PKG_ROOT = Path(__file__).resolve().parents[1]
MODELS_DIR = PKG_ROOT / "models"

# 4x4 is the smallest dictionary, which maximises module size in pixels -- the whole
# point when the camera is 640x480 and the plate is 27 px across at survey altitude.
DICTIONARIES = {"4x4_50": "DICT_4X4_50", "5x5_50": "DICT_5X5_50"}

MODEL_SDF = """\
<?xml version='1.0'?>
<!-- GENERATED by tools/gen_aruco_textures.py. Do not edit by hand. -->
<sdf version="1.6">
    <model name="aruco_marker_{marker_id}">
        <static>true</static>
        <link name="link">
            <visual name="marker">
                <cast_shadows>false</cast_shadows>
                <geometry>
                    <plane>
                        <normal>0 0 1</normal>
                        <size>{size:g} {size:g}</size>
                    </plane>
                </geometry>
                <material>
                    <ambient>1 1 1 1</ambient>
                    <diffuse>1 1 1 1</diffuse>
                    <!-- no highlight: a specular hot spot blows out the black modules
                         and the detector stops seeing the marker -->
                    <specular>0 0 0 1</specular>
                    <pbr>
                        <metal>
                            <albedo_map>materials/textures/aruco_{dictionary}_{marker_id}.png</albedo_map>
                            <metalness>0.0</metalness>
                            <roughness>1.0</roughness>
                        </metal>
                    </pbr>
                </material>
            </visual>
        </link>
    </model>
</sdf>
"""

MODEL_CONFIG = """\
<?xml version="1.0"?>
<!-- GENERATED by tools/gen_aruco_textures.py. Do not edit by hand. -->
<model>
  <name>aruco marker {marker_id}</name>
  <version>1.0</version>
  <sdf version="1.6">model.sdf</sdf>

  <author>
    <name>uavsim</name>
  </author>

  <description>
    A {size:g} m horizontal plate carrying ArUco {dictionary} marker {marker_id},
    face up for a nadir camera. Generated by tools/gen_aruco_textures.py.
  </description>

</model>
"""


def marker_png(dictionary: str, marker_id: int, *, px: int = 600,
               marker_fraction: float = 0.8) -> bytes:
    """One marker centred on a white plate, as PNG bytes.

    ``marker_fraction`` is the marker's share of the plate edge; the remainder is the
    white quiet zone the detector needs to find the marker's outer contour.  At the
    defaults that is a 2.4 m marker with 0.3 m of white on a 3.0 m plate.
    """
    try:
        import cv2
        import numpy as np
    except ImportError as exc:                                  # pragma: no cover
        raise SystemExit(
            "this script needs OpenCV with contrib modules, which is an authoring "
            "dependency only (the generated PNGs are committed):\n"
            "  pip install opencv-contrib-python") from exc

    name = DICTIONARIES[dictionary]
    # 6 modules across including the marker's own black border, so keep the marker
    # side divisible by 6 -- otherwise cv2 resamples and the module edges go grey.
    side = int(round(px * marker_fraction / 6.0)) * 6
    if side <= 0 or side > px:
        raise ValueError(f"marker_fraction {marker_fraction} gives a {side} px marker "
                         f"on a {px} px plate")

    # the two spellings each function has had across OpenCV 4.x -- 4.5 already has
    # getPredefinedDictionary but still calls the draw function drawMarker
    get_dict = getattr(cv2.aruco, "getPredefinedDictionary", None) \
        or cv2.aruco.Dictionary_get
    draw = getattr(cv2.aruco, "generateImageMarker", None) or cv2.aruco.drawMarker
    marker = draw(get_dict(getattr(cv2.aruco, name)), marker_id, side)

    plate = np.full((px, px), 255, dtype=np.uint8)
    off = (px - side) // 2
    plate[off:off + side, off:off + side] = marker
    ok, buf = cv2.imencode(".png", plate)
    if not ok:                                                   # pragma: no cover
        raise RuntimeError(f"could not encode marker {marker_id}")
    return bytes(buf)


def model_files(dictionary: str, marker_id: int, size_m: float) -> dict[str, str]:
    """The text files of one marker model, keyed by path relative to the model dir."""
    fields = {"marker_id": marker_id, "dictionary": dictionary, "size": size_m}
    return {"model.sdf": MODEL_SDF.format(**fields),
            "model.config": MODEL_CONFIG.format(**fields)}


def _parse_ids(spec: str) -> list[int]:
    """``0-7`` or ``0,3,5`` or a mix."""
    ids: list[int] = []
    for part in spec.split(","):
        if "-" in part.strip().lstrip("-"):
            lo, hi = part.split("-")
            ids.extend(range(int(lo), int(hi) + 1))
        else:
            ids.append(int(part))
    return ids


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dict", dest="dictionary", default="4x4_50",
                    choices=sorted(DICTIONARIES))
    ap.add_argument("--ids", default="0-9", help="e.g. 0-9 or 0,3,5 (default: 0-9)")
    ap.add_argument("--px", type=int, default=600, help="plate texture size in pixels")
    ap.add_argument("--marker-fraction", type=float, default=0.8,
                    help="marker's share of the plate edge (default 0.8 -> 0.2 m quiet "
                         "zone on a 2 m plate)")
    ap.add_argument("--size", type=float, default=3.0, help="plate side in metres")
    ap.add_argument("--out-dir", type=Path, default=MODELS_DIR)
    ap.add_argument("--check", action="store_true",
                    help="regenerate in memory and byte-compare; exit 1 on a mismatch")
    args = ap.parse_args(argv)

    stale: list[Path] = []
    written: list[Path] = []
    for marker_id in _parse_ids(args.ids):
        model_dir = args.out_dir / f"aruco_marker_{marker_id}"
        png_path = (model_dir / "materials" / "textures"
                    / f"aruco_{args.dictionary}_{marker_id}.png")
        png = marker_png(args.dictionary, marker_id, px=args.px,
                         marker_fraction=args.marker_fraction)
        texts = model_files(args.dictionary, marker_id, args.size)

        if args.check:
            if not png_path.exists() or png_path.read_bytes() != png:
                stale.append(png_path)
            for rel, text in texts.items():
                path = model_dir / rel
                if not path.exists() or path.read_text() != text:
                    stale.append(path)
            continue

        png_path.parent.mkdir(parents=True, exist_ok=True)
        png_path.write_bytes(png)
        written.append(png_path)
        for rel, text in texts.items():
            (model_dir / rel).write_text(text)
            written.append(model_dir / rel)

    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(PKG_ROOT)}", file=sys.stderr)
        if stale:
            print("regenerate with:\n  python3 tools/gen_aruco_textures.py "
                  f"--dict {args.dictionary} --ids {args.ids}", file=sys.stderr)
            return 1
        print(f"up to date: {len(_parse_ids(args.ids))} aruco marker models")
        return 0

    print(f"wrote {len(written)} files under {args.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
